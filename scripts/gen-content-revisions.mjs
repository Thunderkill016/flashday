/*
 * One-time generator for src/content/revisions.js (A1-ARCH-001).
 *
 * Walks git history for src/content/a1/*.js and records, per chunk, the
 * ordered timeline of content revisions: { rev, since } where `rev` is the
 * deterministic fingerprint of the chunk's target text and `since` is the
 * commit time (ms) when that text first existed.
 *
 * The manifest is a FROZEN record of the pre-fingerprint era — it answers
 * "which phrase did a legacy `lesson:chunk` key refer to at time T?". It is
 * generated once at the migration baseline; content edits after the baseline
 * do NOT need regeneration (post-baseline keys carry the rev inline).
 *
 * Regenerate (repo root, git history required):
 *   node scripts/gen-content-revisions.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, basename } from 'node:path';
import { pathToFileURL } from 'node:url';

// The migration baseline: last commit of the pre-fingerprint era. Revisions
// are pinned to this commit regardless of what lands on main later — later
// texts produce new revs automatically via the inline fingerprint.
const BASELINE = '01377b6d70daffd51252effcb1e8d7c786a7dcc3';
const CONTENT_DIR = 'src/content/a1';
const OUT = 'src/content/revisions.js';

function git(...args) {
  return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

// Same fingerprint as src/core/domain.js contentRev — keep in sync.
// The artifact is the target↔meaning pair: a sense change under the same
// English form is a different component.
function fingerprint(chunk) {
  const t = String(chunk?.target ?? '').trim().toLowerCase().replace(/\s+/g, ' ');
  const m = String(chunk?.meaning ?? '').trim().toLowerCase().replace(/\s+/g, ' ');
  const s = `${t}\u0001${m}`;
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.codePointAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}

const commits = git('log', BASELINE, '--format=%H %ct', '--reverse', '--', CONTENT_DIR)
  .trim().split('\n').filter(Boolean)
  .map((line) => {
    const [sha, ct] = line.split(' ');
    return { sha, ms: Number(ct) * 1000 };
  });

const history = {}; // lessonId → chunkId → [{rev, since}]
const tmp = mkdtempSync(join(tmpdir(), 'fd-rev-'));
try {
  for (const { sha, ms } of commits) {
    const files = git('ls-tree', '-r', '--name-only', sha, '--', CONTENT_DIR)
      .trim().split('\n').filter((f) => /s\d+-l\d+\.js$/.test(f));
    for (const file of files) {
      const src = git('show', `${sha}:${file}`);
      const tmpFile = join(tmp, `${basename(file, '.js')}-${sha.slice(0, 10)}.mjs`);
      writeFileSync(tmpFile, src);
      let lesson;
      try {
        lesson = (await import(pathToFileURL(tmpFile).href)).default;
      } catch (error) {
        console.warn(`skip ${file}@${sha.slice(0, 8)}: ${error.message}`);
        continue;
      }
      if (!lesson?.id || !Array.isArray(lesson.chunks)) continue;
      const perChunk = (history[lesson.id] ||= {});
      for (const chunk of lesson.chunks) {
        if (typeof chunk?.id !== 'string' || typeof chunk?.target !== 'string') continue;
        const rev = fingerprint(chunk);
        const segments = (perChunk[chunk.id] ||= []);
        const last = segments[segments.length - 1];
        if (!last) segments.push({ rev, since: ms });
        else if (last.rev !== rev) segments.push({ rev, since: ms });
      }
    }
  }
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const lessons = Object.keys(history).sort();
let changed = 0;
const lines = [];
for (const lessonId of lessons) {
  const chunks = Object.keys(history[lessonId]).sort();
  const entries = chunks.map((chunkId) => {
    const segs = history[lessonId][chunkId];
    if (segs.length > 1) changed++;
    return `    ${JSON.stringify(chunkId)}: ${JSON.stringify(segs)}`;
  });
  lines.push(`  ${JSON.stringify(lessonId)}: {\n${entries.join(',\n')}\n  }`);
}

const out = `/*
 * GENERATED by scripts/gen-content-revisions.mjs — do not edit by hand.
 * Frozen revision ledger of the pre-fingerprint era (baseline ${BASELINE}).
 * CHUNK_REVISION_HISTORY[lessonId][chunkId] = [{ rev, since }] ordered by
 * time; \`since\` is the commit time (ms) when that target text first
 * existed. Legacy rev-less keys resolve through this at replay.
 */
export const CHUNK_REVISION_HISTORY = Object.freeze({
${lines.join(',\n')}
});
`;
writeFileSync(OUT, out);
console.log(`${OUT}: ${lessons.length} lessons, ${changed} chunks with >1 revision`);
